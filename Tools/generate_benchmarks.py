#!/usr/bin/env python3
"""Writes the table of what everybody else has made of each level.

The game has no back end. It sends counting out to TelemetryDeck and never asks anything
back, so the only way the map can say "most players three-star this one" is to be told
before it ships. This bakes that in: one row per level, counted off the `Level.held`
signal every held pen has sent since 1.0.

Three figures per level, all of them players rather than pens — a player who took a level
apart twenty times counts once:

  * `held`      — players who have ever held a pig in it.
  * `threeStar` — how many of those got three stars out of it.
  * `bestPen`   — how many of those found the best pen the map has in it.

`threeStar` works because stars are a best-ever mark and every attempt sends its own
signal: a player whose best is three has sent at least one `stars:3`, and one who never
managed it has sent none. The same goes for `bestPen`.

Run it in two steps, because the query wants a token this repository does not carry:

    Tools/generate_benchmarks.py --query > benchmarks.tql.json
    # run that against TelemetryDeck — the query editor in the dashboard, or the API —
    # and save the response
    Tools/generate_benchmarks.py --from benchmarks.json

It writes `Pigpen/Models/LevelBenchmarks.swift`, which is generated and committed, stamped
with the day it was taken.

The release workflow runs

    Tools/generate_benchmarks.py --check

which fails when that stamp has gone stale, so a build cannot go out with a table nobody
remembered to regenerate. Age rather than accuracy, because accuracy cannot be checked from
CI: knowing whether the figures have moved means asking TelemetryDeck, and that wants a
read token this repository does not carry. Age catches what actually goes wrong.
"""

import argparse
import json
import os
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Pigpen/Models/LevelBenchmarks.swift"

# How old the table may be before a release refuses to go out with it.
#
# A week, which is shorter than the gap between any two releases — so in practice this does
# not catch a table that has drifted, it makes regenerating part of cutting a release. That
# is the point: the alternative is a threshold generous enough to pass most of the time,
# which is a check that only fires when somebody has already forgotten for a season.
#
# `ALLOW_STALE_BENCHMARKS=1` is the way past it for a release that cannot wait on the
# dashboard — a hotfix, or a day when TelemetryDeck is unreachable.
MAX_AGE_DAYS = 7

# The one query the table comes out of. `thetaSketch` on `clientUser` counts players and
# not signals, and the two filtered copies of it count the players inside that set who
# ever sent a three-star pen and who ever sent the best pen there is.
#
# `dataSource`, `baseFilters` and `appID` are deliberately absent: the dashboard fills
# them in, and the API wants them set to the app being asked about.
QUERY = {
    "queryType": "groupBy",
    "dimensions": [{"type": "default", "dimension": "level", "outputName": "level"}],
    "filter": {"type": "selector", "dimension": "type", "value": "Level.held"},
    "aggregations": [
        {"type": "thetaSketch", "fieldName": "clientUser", "name": "held"},
        {
            "type": "filtered",
            "filter": {"type": "selector", "dimension": "stars", "value": "3"},
            "aggregator": {"type": "thetaSketch", "fieldName": "clientUser", "name": "threeStar"},
        },
        {
            "type": "filtered",
            "filter": {"type": "selector", "dimension": "bestPen", "value": "true"},
            "aggregator": {"type": "thetaSketch", "fieldName": "clientUser", "name": "bestPen"},
        },
    ],
    "granularity": "all",
    "relativeIntervals": [
        {
            "beginningDate": {"component": "day", "offset": -720, "position": "beginning"},
            "endDate": {"component": "day", "offset": 0, "position": "end"},
        }
    ],
}

HEADER = """// Generated by Tools/generate_benchmarks.py on {generated} — do not edit by hand.
//
// Re-run the tool to change what is in here:
//
//     Tools/generate_benchmarks.py --query > benchmarks.tql.json
//     Tools/generate_benchmarks.py --from benchmarks.json
//
/// What everybody else has made of each level: how many players have ever held a pig in it,
/// how many of them got three stars out of it, and how many found the best pen it has.
///
/// Baked in rather than fetched. The game has no back end and asks nothing about anybody at
/// run time; this is what the counting knew when the build was cut, carried along with it.
/// It goes stale the way any photograph does, which is why nothing reads a row of it without
/// also saying how many players the row stands on.
enum LevelBenchmarks {
    /// How many players a level needs behind it before the game will say anything about them
    /// out loud.
    ///
    /// A level two people have played can only report halves and wholes, and "half of players"
    /// out of a sample of two is not a fact about players — it is a fact about the two. Below
    /// this the record panel shows a player their own row and stays quiet about the field,
    /// which is the only honest thing to do with a number that thin. The early worlds clear it
    /// long before the late ones do, and a world where nothing clears it says so in one line
    /// rather than printing nine shrugs.
    static let quorum = 12

    /// The day this table was taken off the counting, as `YYYY-MM-DD`.
    ///
    /// Here because a baked-in photograph needs a date on the back of it. The release workflow
    /// reads it and refuses to cut a build whose table has gone stale — which is the only kind
    /// of staleness anything can check without a read token for TelemetryDeck, and the only
    /// kind worth checking anyway: what goes wrong is nobody remembering to regenerate, not
    /// the figures being subtly wrong.
    static let generated = "{generated}"

    /// Every level the counting has ever seen a held pen on, by level id. A level nobody has
    /// reached yet is simply absent.
    static let all: [String: LevelBenchmark] = [
"""

FOOTER = """    ]

    /// What the field has made of a level, and nothing at all for one too few players have
    /// reached to speak for. Callers show the player's own record either way; this only ever
    /// adds a second line beside it.
    static func benchmark(for levelID: String) -> LevelBenchmark? {
        guard let benchmark = all[levelID], benchmark.held >= quorum else { return nil }
        return benchmark
    }
}

/// One level's row: the players who have held it, and how many of them got the two things
/// worth getting out of it.
///
/// The two shares are of the players who held it rather than of everybody playing, since a
/// level nobody has reached has nothing to say about the people who have not reached it.
struct LevelBenchmark: Equatable, Sendable {
    /// Players who have ever held a pig in this level.
    let held: Int
    /// How many of those got three stars out of it.
    let threeStar: Int
    /// How many of those found the best pen the map has in it.
    let bestPen: Int

    /// The share of players who three-starred it, between 0 and 1.
    var threeStarShare: Double { held > 0 ? Double(threeStar) / Double(held) : 0 }
    /// The share of players who found its best pen, between 0 and 1.
    var bestPenShare: Double { held > 0 ? Double(bestPen) / Double(held) : 0 }
}
"""


def rows(response):
    """Pulls (level, held, threeStar, bestPen) out of a TQL groupBy response.

    Druid wraps each group in an envelope with the figures under `event`; a response saved
    straight out of the dashboard is that list, and one saved from the API may have it under
    `result`. Both are accepted because both are what people actually end up with.
    """
    if isinstance(response, dict):
        response = response.get("result", response)
    if not isinstance(response, list):
        raise SystemExit("error: expected a list of groups, or an object with `result` in it")

    found = {}
    for group in response:
        event = group.get("event", group) if isinstance(group, dict) else {}
        level = event.get("level")
        if not level:
            continue
        held = int(event.get("held", 0))
        if held <= 0:
            continue
        # Clamped rather than trusted: a theta sketch is an estimate, and an estimate of a
        # subset can in principle come back a hair above the set it is a subset of. A row
        # claiming more three-star players than players would print as 110% on a card.
        found[level] = (
            held,
            min(int(event.get("threeStar", 0)), held),
            min(int(event.get("bestPen", 0)), held),
        )
    if not found:
        raise SystemExit("error: no levels in that response")
    return found


STAMP = re.compile(r'static let generated = "(\d{4}-\d{2}-\d{2})"')


def generated_on():
    """The day the committed table was taken off the counting."""
    if not OUT.exists():
        raise SystemExit(f"error: {OUT.relative_to(ROOT)} is missing — run --from to write it")
    found = STAMP.search(OUT.read_text())
    if not found:
        raise SystemExit(
            f"error: no generation date in {OUT.relative_to(ROOT)} — regenerate it with --from"
        )
    return date.fromisoformat(found.group(1))


def check(max_age_days):
    """Fails when the committed table has gone stale, for the release workflow to call.

    Age and not accuracy, because accuracy cannot be checked here: knowing whether the figures
    have moved means asking TelemetryDeck, and that wants a token this repository does not
    carry. Age catches the thing that actually goes wrong, which is a release going out with a
    table nobody remembered to regenerate.

    A stale table is never *wrong* — a level below the quorum simply stays quiet, so the panel
    falls back to showing a player their own record. That is why this is worth a nag at release
    time and not much more, and why `ALLOW_STALE_BENCHMARKS=1` exists: a hotfix should not be
    held up by a statistics table.
    """
    taken = generated_on()
    age = (date.today() - taken).days
    print(f"{OUT.relative_to(ROOT)}: generated {taken.isoformat()}, {age} days ago")

    if age <= max_age_days:
        return
    if os.environ.get("ALLOW_STALE_BENCHMARKS") == "1":
        print(f"warning: older than {max_age_days} days, allowed by ALLOW_STALE_BENCHMARKS=1")
        return

    raise SystemExit(
        f"\nerror: the benchmark table is {age} days old, and releases want it inside "
        f"{max_age_days}.\n\n"
        "What the panel at the foot of each trail says about other players comes out of this\n"
        "table, and it is a photograph rather than a feed. Regenerate it:\n\n"
        "    Tools/generate_benchmarks.py --query > benchmarks.tql.json\n"
        "    # run that against TelemetryDeck, save the response\n"
        "    Tools/generate_benchmarks.py --from benchmarks.json\n\n"
        "then commit the result and re-tag. To ship without regenerating — a hotfix, or a\n"
        "release where nobody can reach the dashboard — set ALLOW_STALE_BENCHMARKS=1.\n"
    )


def swift(found):
    # A plain substitution rather than str.format, since the header is full of Swift braces.
    lines = [HEADER.replace("{generated}", date.today().isoformat())]
    for level in sorted(found):
        held, three, best = found[level]
        lines.append(
            f'        "{level}": LevelBenchmark(held: {held}, threeStar: {three}, bestPen: {best}),\n'
        )
    lines.append(FOOTER)
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--query",
        action="store_true",
        help="print the TQL query to run against TelemetryDeck, and stop",
    )
    parser.add_argument(
        "--from",
        dest="source",
        help="the saved query response to build the table from, or - for stdin",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed table has gone stale; what the release workflow runs",
    )
    parser.add_argument(
        "--max-age-days",
        type=int,
        default=MAX_AGE_DAYS,
        help=f"how old the table may be before --check fails (default {MAX_AGE_DAYS})",
    )
    args = parser.parse_args()

    if args.query:
        print(json.dumps(QUERY, indent=2))
        return

    if args.check:
        check(args.max_age_days)
        return

    if not args.source:
        parser.error("one of --query, --from or --check is needed")

    text = sys.stdin.read() if args.source == "-" else Path(args.source).read_text()
    found = rows(json.loads(text))
    OUT.write_text(swift(found))

    speaking = sum(1 for held, _, _ in found.values() if held >= 12)
    print(f"{OUT.relative_to(ROOT)}: {len(found)} levels, {speaking} of them above the quorum")


if __name__ == "__main__":
    main()
